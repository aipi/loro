// One front-matter line replaced by `wanted`, or None when there is nothing to
// do: already current, no such line, or a value the user wrote (only a string
// Loro itself shipped is ever rewritten).
fn refreshed_line(on_disk: &str, key: &str, wanted: &str, legacy: &[&str]) -> Option<String> {
    let line = field_line(on_disk, key)?;
    let current = line[key.len()..].trim();
    if current == wanted || !legacy.contains(&current) {
        return None;
    }
    Some(on_disk.replacen(line, &format!("{key} {wanted}"), 1))
}

// The on-disk skill with its description line replaced by the shipped one.
pub fn refreshed_description(on_disk: &str, shipped: &str) -> Option<String> {
    let wanted = skill_description(shipped)?;
    refreshed_line(
        on_disk,
        "description:",
        wanted,
        &SHIPPED_LEGACY_DESCRIPTIONS,
    )
}

// Both user-visible lines at once — what the seeding path applies to a skill that
// already exists on disk.
pub fn refreshed_front_matter(on_disk: &str, shipped: &str) -> Option<String> {
    let desc = refreshed_description(on_disk, shipped);
    let base = desc.as_deref().unwrap_or(on_disk);
    let hint = skill_argument_hint(shipped)
        .and_then(|wanted| refreshed_line(base, "argument-hint:", wanted, &SHIPPED_LEGACY_HINTS));
    hint.or(desc)
}

