// ---- the user-visible lines of a habilidade ---------------------------------
// A skill's front matter is not agent-only. Two of its lines are printed
// verbatim by the app: `description:` (the sidebar tooltip and the sentence in
// the "usar" sheet) and `argument-hint:` (the sheet's "argumentos: …" line and
// the placeholder of the field the user types into). Both are UI copy and
// DESIGN.md §4 governs them (no acervo/fila/brainstorming/contexto, no ADR
// number the user cannot act on, no "relatório" — ADR-0018 removed that
// artefact). What the agent needs is stated in each skill's BODY, which spells
// out the exact paths it accepts.

fn front_matter(body: &str) -> Option<&str> {
    let rest = body.strip_prefix("---\n")?;
    let end = rest.find("\n---")?;
    Some(&rest[..end])
}

fn field_line<'a>(body: &'a str, key: &str) -> Option<&'a str> {
    front_matter(body)?.lines().find(|l| l.starts_with(key))
}

fn field_value<'a>(body: &'a str, key: &str) -> Option<&'a str> {
    field_line(body, key).map(|l| l[key.len()..].trim())
}

pub fn skill_description(body: &str) -> Option<&str> {
    field_value(body, "description:")
}

pub fn skill_argument_hint(body: &str) -> Option<&str> {
    field_value(body, "argument-hint:")
}

