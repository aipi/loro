    // ADR-0026 §10 — the reading protocol gained the step the measurement asked
    // for. Jumping to ONE section by term match landed on the right one 36% of the
    // time; card-routed section PLUS the facts section (§5) lands 73%, at 17 KB per
    // question against 87 KB for reading whole files. The protocol says both: use
    // an exact locator when one exists, and read §5 alongside the guess when none
    // does — because a guessed section is a guess, and §5 is where a consolidated
    // fact lives by the mold's own definition.
    // The needles are matched on whitespace-collapsed text: the rule is prose that
    // gets rewrapped, and a test that breaks on a line wrap teaches nothing.
    fn flat(s: &str) -> String {
        s.split_whitespace().collect::<Vec<_>>().join(" ")
    }

    #[test]
    fn agents_teaches_reading_a_section_with_the_facts_section() {
        for lang in ["pt", "en"] {
            let agents = flat(&agents_template(&["frota".into()], lang));
            let (facts, exact) = if lang == "en" {
                (
                    "together with section 5",
                    "`H-YYYY-MM-DD-…` is in section 6",
                )
            } else {
                ("junto com a seção 5", "`H-AAAA-MM-DD-…` está na seção 6")
            };
            assert!(
                agents.contains(facts),
                "agents [{lang}] does not send the reader to the facts section"
            );
            assert!(
                agents.contains(exact),
                "agents [{lang}] does not teach that an id already addresses its section"
            );
        }
    }

    // Only the skills that read the CONTEXTS carry this rule. /loro-slack reads the
    // annotation sidecar and /loro-tool writes a skill — their cheap-reading rule is
    // about their own surface, and forcing §5 on them would be cargo cult.
    #[test]
    fn skills_teach_reading_a_section_with_the_facts_section() {
        // The filter is the BEHAVIOUR, not the rule's label: a skill that tells the
        // reader to start from the index is a skill that has to land somewhere.
        for (lang, index, facts) in [
            ("pt", "comece pelo `INDEX.md`", "seção 5"),
            ("en", "start from `INDEX.md`", "section 5"),
        ] {
            let mut checked = 0;
            for (name, skill) in builtin_skills(lang) {
                let flat_skill = flat(skill);
                if !flat_skill.contains(index) {
                    continue;
                }
                assert!(
                    flat_skill.contains(facts),
                    "skill {name} [{lang}] routes by INDEX.md but never reaches the facts section"
                );
                checked += 1;
            }
            assert!(checked >= 5, "[{lang}] only {checked} skills were checked");
        }
    }

